# --- MAIN PIPELINE EXECUTION ---
# ===============================================================================
def execute_pipeline(args, spark, glueContext):
    
    def get_text_arg(name, default_val):
        for i, val in enumerate(sys.argv):
            if val == f"--{name}" and len(sys.argv) > i + 1:
                return sys.argv[i + 1]
        return default_val

    target_headers_raw = args.get('target_headers', '')
    row_number_label = args.get('row_number_label', '')
    input_file_name = args['input_file_name']
    input_path = args['input_file_path'] + input_file_name
    connection_name = args['connection_name']
    xform_ctx_jobname = args['JOB_NAME']
    target_raw = args['target_table']
    audit_target_raw = get_text_arg('audit_table', None)
    
    # ---------------------------------------------------------
    #   DERIVE BILL CYCLE & FILENAME
    # ---------------------------------------------------------
    file_name_no_ext = os.path.splitext(input_file_name)[0]
    billcycle_val = "BC"+file_name_no_ext[-2:]

    print(f"### -Reading Excel file: {input_path} at {datetime.now()}")
    
    # ===============================================================================
    # --- READ AND EXPAND DATA ---
    # ===============================================================================
    try:
        spark_df = (
            spark.read.format("com.crealytics.spark.excel")
            .option("header", "false")
            .option("inferSchema", "false")
            .option("treatEmptyValuesAsNulls", "false")
            .option("dataAddress", "A1")
            .option("useHeaderRowIndex", "false")
            .load(input_path)
        )

    except AnalysisException as e:
        if "Path does not exist" in str(e):
            raise_custom_error("missing_file", "S3 object not found or access denied", input_path)
        else:
            raise e
            
    # STAMP ORIGINAL ORDER STRICTLY (1, 2, 3...)
    from pyspark.sql.window import Window
    from pyspark.sql.functions import row_number, lit
    window_spec = Window.orderBy(lit(1))
    spark_df = spark_df.withColumn("_temp_row_num", row_number().over(window_spec))
        
    # INGESTION TYPE ROUTER (FLAT or HEADED path)
    if target_headers_raw:
        print(f"### -Target headers detected. Routing to HEADED mode...")
        raw_headers_list = target_headers_raw.split(",")
        s3_dyf = DynamicFrame.fromDF(spark_df, glueContext, "s3_dyf")
        transform_collection = MyTransform(glueContext, DynamicFrameCollection({"s3_dyf": s3_dyf}, glueContext), raw_headers_list)
        
        from awsglue.transforms import SelectFromCollection
        transformed_dyf = SelectFromCollection.apply(
            dfc=transform_collection, 
            key=list(transform_collection.keys())[0], 
            transformation_ctx="xformed_dyf-" + xform_ctx_jobname
        )
        final_df = transformed_dyf.toDF()

        row_count = final_df.count()
        if row_count == 0 or "No_Data_Found" in final_df.columns:
            print("### -Fuzzy matcher failed or sheet is blank")
            raise_custom_error("empty_data", "Fuzzy matcher failed or sheet is blank", input_path)

    else:
        print("### -No target headers detected. Routing to FLAT sequential mode...")
        data_columns = [c for c in spark_df.columns if c != "_temp_row_num"]
        new_column_names = [f"column{i+1}" for i in range(len(data_columns))]

        mapping_exprs = [col(old_name).alias(new_name) for old_name, new_name in zip(data_columns, new_column_names)]
        mapping_exprs.append(col("_temp_row_num")) 
        final_df = spark_df.select(*mapping_exprs)

    # STRICT ORDERING
    # Retain _temp_row_num here so the Audit table can use it
    final_df = (
        final_df.coalesce(1)
        .orderBy(col("_temp_row_num").asc())
    )

    # Cache the DataFrame because of writing to 2 different tables
    final_df.cache()

    # ===============================================================================
    # --- CONNECTION SETUP ---
    # ===============================================================================
    jdbc_url, connection_properties = get_postgres_jdbc_conf(glueContext, connection_name)

    def quote_table(raw_name):
        if "." in raw_name:
            schema_part, table_part = raw_name.split(".", 1)
            return f'"{schema_part}"."{table_part}"'
        return f'"{raw_name}"'

    quoted_target_table = quote_table(target_raw)

    # ===============================================================================
    # --- DBWRITE 1: MAIN DATA TABLE ---
    # ===============================================================================
    print(f"### -Preparing primary write to {quoted_target_table}...")
    
    # Drop the temp row num only for the 1st table's write process
    main_write_df = final_df.drop("_temp_row_num")

    try:
        target_schema_df = spark.read.jdbc(
            url=jdbc_url,
            table=quoted_target_table,
            properties=connection_properties
        )
        target_columns = target_schema_df.columns
        final_columns_lower = [c.lower() for c in main_write_df.columns]
        
        skip_label = row_number_label.lower() if row_number_label else None
        
        for t_col in target_columns:
            if skip_label and t_col.lower() == skip_label:
                continue
            if t_col.lower() not in final_columns_lower:
                main_write_df = main_write_df.withColumn(t_col, lit(None).cast("string"))
        
        columns_to_select = []
        for t_col in target_columns:
            if skip_label and t_col.lower() == skip_label:
                continue
            matched_col = next((c for c in main_write_df.columns if c.lower() == t_col.lower()), t_col)
            columns_to_select.append(col(matched_col).alias(t_col))
                
        main_write_df = main_write_df.select(*columns_to_select)
        
    except Exception as e:
        print(f"### -Warning: Could not fetch schema. Proceeding. Error: {str(e)}")

    try:
        main_write_df.write \
            .option("truncate", "true") \
            .jdbc(
                url=jdbc_url,
                table=quoted_target_table,
                mode="overwrite", 
                properties=connection_properties
            )
        print("### -SUCCESS: Primary table loaded in strict sequential order.")

    except Exception as e:
        raise_custom_error("database_error", f"Primary write failed for {target_raw}: {str(e)[:100]}...", input_path)

    # ===============================================================================
    # --- DBWRITE 2: AUDIT TABLE (PARTIAL TRUNCATE) ---
    # ===============================================================================
    if audit_target_raw:
        quoted_audit_table = quote_table(audit_target_raw)
        print(f"### -Preparing audit write to {quoted_audit_table} with Bill Cycle: '{billcycle_val}'...")
        
        # Execute Partial Truncate (DELETE) via imported helper
        delete_query = f"DELETE FROM {quoted_audit_table} WHERE billcycle = '{billcycle_val}'"
        try:
            execute_postgres_query(glueContext, jdbc_url, connection_properties, delete_query)
        except Exception as e:
            raise_custom_error("audit_delete_error", f"Failed to delete old audit records: {str(e)}", input_path)

        # Construct Audit DataFrame
        audit_df = final_df.select(
            "*", 
            lit(billcycle_val).alias("billcycle"),
            lit(input_file_name).alias("filename"),
            uuidv7_udf().alias("sequencialid"),
            current_timestamp().alias("dateprocessed")
        ).withColumnRenamed("_temp_row_num", "rownumber")

        # Audit Schema Alignment
        try:
            audit_schema_df = spark.read.jdbc(url=jdbc_url, table=quoted_audit_table, properties=connection_properties)
            
            existing_cols_lower = [c.lower() for c in audit_df.columns]
            
            for a_col in audit_schema_df.columns:
                if a_col.lower() not in existing_cols_lower:
                    audit_df = audit_df.withColumn(a_col, lit(None).cast("string"))
                    
            audit_cols_to_select = [c for c in audit_schema_df.columns]
            audit_df = audit_df.select(*audit_cols_to_select)
            
        except Exception as e:
            print(f"### -Warning: Audit schema alignment skipped: {str(e)}")

        # Inject stringtype directly into the URL so the Postgres driver cannot ignore it
        separator = "&" if "?" in jdbc_url else "?"
        audit_jdbc_url = f"{jdbc_url}{separator}stringtype=unspecified"
        
        # Write via Append
        try:
            audit_df.write.jdbc(
                url=audit_jdbc_url, table=quoted_audit_table, mode="append", properties=connection_properties
            )
            print("### -SUCCESS: Audit table loaded via Append.")
        except Exception as e:
            raise_custom_error("audit_write_error", f"Audit write failed: {str(e)[:100]}...", input_path)
            
    # Uncache memory
    final_df.unpersist()