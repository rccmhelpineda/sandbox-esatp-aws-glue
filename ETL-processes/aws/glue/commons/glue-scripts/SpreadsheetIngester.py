# --- SPARK-NATIVE DATA TRANSFORM (HEADED MODE) ---
# ===============================================================================
def MyTransform(glueContext, dfc, target_headers_list) -> DynamicFrameCollection:
    target_headers = [norm(h) for h in target_headers_list if norm(h)]
    
    input_df_name = list(dfc.keys())[0]
    input_dyf = dfc.select(input_df_name)
    spark_df = input_dyf.toDF()
    
    data_cols = [c for c in spark_df.columns if c != "_temp_row_num"]
    num_cols = len(data_cols)
    
    sample_df = spark_df.limit(50)
    all_rows = sample_df.collect()

    col_mapping, header_end_index, best_match_count = optimized_header_match(all_rows, target_headers, num_cols)
    print(f"### -Universal Fuzzy Detector matched {best_match_count}/{len(target_headers)} headers ending at row index {header_end_index}.")

    if header_end_index >= 0 and col_mapping:
        data_start_index = header_end_index + 1
        sorted_cols = sorted(col_mapping.keys())
        
        data_df = spark_df.rdd.zipWithIndex().filter(
            lambda row_with_index: row_with_index[1] >= data_start_index
        ).map(lambda row_with_index: row_with_index[0])
        
        data_df = glueContext.spark_session.createDataFrame(data_df, spark_df.schema)
        
        footer_keywords = ['report creator', 'page ', 'run time', 'generated by', 'end of report', 'confidential', 'rows selected']
        footer_pattern = "(?i)(" + "|".join(footer_keywords) + ")"
        
        footer_condition = lit(False)
        non_empty_condition = lit(False)
        
        for c in range(num_cols):
            col_name = data_df.columns[c]
            safe_col = coalesce(col(col_name).cast("string"), lit(""))
            
            footer_condition = footer_condition | safe_col.rlike(footer_pattern)
            non_empty_condition = non_empty_condition | (safe_col != "")
        
        filtered_data_df = data_df.filter(non_empty_condition & ~footer_condition)
        
        selected_columns = []
        for c in sorted_cols:
            original_col_name = data_df.columns[c]
            target_col_name = clean_col_name(col_mapping[c])
            selected_columns.append(trim(col(original_col_name)).alias(target_col_name))
        
        selected_columns.append(col("_temp_row_num"))
        final_df = filtered_data_df.select(*selected_columns)
            
    else:
        schema = StructType([StructField("No_Data_Found", StringType(), True)])
        final_df = glueContext.spark_session.createDataFrame([["No valid data range found"]], schema)

    result_dyf = DynamicFrame.fromDF(final_df, glueContext, "extracted_data")
    return DynamicFrameCollection({"CustomTransform0": result_dyf}, glueContext)


